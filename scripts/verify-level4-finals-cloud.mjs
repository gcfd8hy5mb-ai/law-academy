import assert from 'node:assert/strict';
import {FINAL_IDS,FINALS_KEY,normalizeFinals,mergeFinals} from './law-finals-cloud-plan.mjs';
const raw=o=>JSON.stringify(o);
const a=raw({'L4-1-FINAL2':{draft:'phone draft',ratings:[null,null,null,null,null,null],snapshots:[{draft:'draft 1',at:'2026-11-09'}]}});
const b=raw({'L4-2-FINAL2':{draft:'computer draft',finished:true}});
assert.equal(FINAL_IDS.length,7);assert.equal(FINALS_KEY,'law-academy-level4-finals-v1');
assert.equal(normalizeFinals(a)['L4-1-FINAL2'].draft,'phone draft');
const disjoint=mergeFinals(a,b);
assert.equal(disjoint.safe,true);assert.equal(disjoint.additions.length,1);
assert.equal(disjoint.deviceOnly.length,1);
assert.equal(JSON.parse(disjoint.merged)['L4-2-FINAL2'].draft,'computer draft');
assert.equal(JSON.parse(disjoint.merged)['L4-1-FINAL2'].draft,'phone draft');
assert.deepEqual(mergeFinals(a,a).conflicts,[]);
assert.equal(mergeFinals(null,a).safe,true);
assert.equal(mergeFinals(a,null).safe,true);
const conflict=mergeFinals(a,raw({'L4-1-FINAL2':{draft:'computer changed independently'}}));
assert.equal(conflict.safe,false);
assert.deepEqual(conflict.conflicts,['L4-1-FINAL2']);
assert.equal(conflict.merged,null);
const benignReorder=raw({'L4-1-FINAL2':{snapshots:[{at:'2026-11-09',draft:'draft 1'}],ratings:[null,null,null,null,null,null],draft:'phone draft'}});
assert.equal(mergeFinals(a,benignReorder).safe,true);
assert.throws(()=>normalizeFinals(raw({'unexpected':{draft:'x'}})),/Unexpected/);
assert.throws(()=>normalizeFinals('{invalid'),/Invalid/);
assert.throws(()=>normalizeFinals(raw({'L4-1-FINAL2':{draft:45}})),/Invalid/);
assert.throws(()=>normalizeFinals(raw({'L4-1-FINAL2':{snapshots:[{bad:'x'}]}})),/Invalid/);
assert.throws(()=>normalizeFinals(raw({'L4-1-FINAL2':{ratings:[111,0,0,0,0,0]}})),/Invalid/);
console.log('PASS — seven-final cloud schema: valid records, disjoint merges, same-exam conflict block, malformed data and score guards');
